// Fictional DOCX and the isolated UI database only; existing real projects are untouched.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require('playwright');
(async () => {
  const base='http://127.0.0.1:8001', credentials=JSON.parse(fs.readFileSync('runtime/workbench-ui.json','utf8'));
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const context=await browser.newContext({viewport:{width:1440,height:900}}), page=await context.newPage();
  const checks=[], errors=[], output='runtime/source-open-review';
  fs.mkdirSync(output,{recursive:true});
  const check=(name,value=true)=>{assert.ok(value,name);checks.push(name);};
  page.on('pageerror',error=>errors.push(error.message));
  async function select(first,last) {
    await page.locator('[data-source-text]').nth(first).scrollIntoViewIfNeeded();
    await page.evaluate(({first,last})=>{
      const nodes=document.querySelectorAll('[data-source-text]'), range=document.createRange();
      range.setStart(nodes[first],0);range.setEnd(nodes[last],nodes[last].childNodes.length);
      const selection=getSelection();selection.removeAllRanges();selection.addRange(range);
      document.querySelector('[data-source-reading]').dispatchEvent(new MouseEvent('mouseup',{bubbles:true}));
    },{first,last});
    await page.locator('[data-source-selection-text]').waitFor({state:'visible'});
  }
  async function save() {
    const response=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().includes('/annotations/'));
    await page.locator('[data-source-save]').click();
    assert.equal((await response).status(),200);
    await page.waitForFunction(()=>document.querySelector('[data-source-status]').dataset.kind==='success');
  }
  try {
    await page.goto(base+'/login/');
    await page.locator('[name=username]').fill(credentials.username);
    await page.locator('[name=password]').fill(credentials.password);
    await Promise.all([page.waitForURL(base+'/'),page.getByRole('button',{name:'登录',exact:true}).click()]);
    await page.goto(base+'/projects/new/');
    await page.locator('[name=name]').fill('原文选段演示 · 虚构资料 '+Date.now());
    await page.getByRole('button',{name:'创建项目',exact:true}).click();
    await page.waitForURL(/\/p\/\d+\/$/);
    const project=Number(page.url().match(/\/p\/(\d+)\//)[1]);
    await page.goto(`${base}/p/${project}/materials/`);
    await page.locator('input[type=file]').setInputFiles('runtime/fictional-policy.docx');
    await page.getByRole('button',{name:'上传并预览 →',exact:true}).click();
    await page.getByRole('button',{name:'确认导入',exact:true}).click();
    await page.waitForURL(/\/source-coding\//);
    check('After import, no mandatory presegmentation or codebook upload');
    await page.getByRole('button',{name:'开始编码 →',exact:true}).click();
    await page.waitForURL(/\/r\/\d+\//);
    await page.locator('[data-source-coding]').waitFor();
    const workbench=page.url(), round=Number(workbench.match(/\/r\/(\d+)\//)[1]);
    check('Compact workspace is at the top',(await page.locator('[data-source-coding]').boundingBox()).y<=100);
    check('Empty codebook permits reading and adding the first code',await page.locator('[data-source-new-code]').isVisible());
    await select(1,2);
    const selected=await page.locator('[data-source-selection-text]').innerText();
    check('Cross-paragraph range keeps Unicode and text',selected.includes('😀')&&selected.includes('第1条')&&selected.includes('第2条'));
    await page.locator('#source-code-name').fill('核对资料与证据');
    await page.locator('[data-source-code-form] button').click();
    await page.locator('[data-source-code-list] [name=primary]:checked').waitFor();
    check('A name-only new code is immediately usable',await page.locator('[data-source-save]').isEnabled());
    await page.locator('#source-note').fill('虚构验收：保留原文中的核对依据。');
    const scroll=await page.locator('[data-source-reading]').evaluate(e=>e.scrollTop);
    await save();
    check('Save retains reading position',Math.abs(await page.locator('[data-source-reading]').evaluate(e=>e.scrollTop)-scroll)<2);
    check('Save retains the selected fragment and code',await page.locator('[data-source-selection-text]').innerText()===selected&&await page.locator('[name=primary]:checked').count()===1);
    check('Saved range is highlighted without duplicating original text',await page.locator('mark[data-source-annotations]').count()>=2);
    check('Highlighting preserves every original paragraph exactly',await page.evaluate(()=>{
      const data=JSON.parse(document.getElementById('source-coding-data').textContent);
      return [...document.querySelectorAll('[data-source-text]')].every((node,index)=>node.textContent===data.blocks[index].text);
    }));
    await select(1,2);
    check('Reselecting the same range opens the saved record',await page.locator('[data-source-selection-position]').innerText().then(t=>t.includes('已保存')));
    await select(3,3);
    check('A new fragment clears prior code and notes',await page.locator('[name=primary]:checked').count()===0&&await page.locator('#source-note').inputValue()==='');
    await page.locator('[name=primary]').first().check();
    await page.locator('#source-note').fill('第二个独立片段');
    await page.getByRole('link',{name:'材料',exact:true}).click();
    await page.locator('[data-source-unsaved]').waitFor({state:'visible'});
    await page.locator('[data-source-leave-cancel]').click();
    check('Cancel leave retains unsaved judgment',page.url()===workbench&&await page.locator('#source-note').inputValue()==='第二个独立片段');
    await save();
    check('Two saved fragments are listed',await page.locator('[data-source-count]').innerText()==='2');
    await page.screenshot({path:output+'/workbench-desktop.png'});
    await page.getByLabel('工作台工具',{exact:true}).click();
    await page.locator('[data-source-history-open]').click();
    await page.locator('.source-history-event').waitFor();
    check('History retains the saved explanation',(await page.locator('[data-source-history-content]').innerText()).includes('第二个独立片段'));
    check('Modification history is accessible',await page.locator('[data-source-history]').isVisible());
    await page.locator('[data-source-history-close]').click();
    await page.keyboard.press('Escape');
    await page.locator('[data-source-complete]').click();
    await page.getByRole('button',{name:'继续编辑本份材料',exact:true}).waitFor();
    check('Completion updates material progress',await page.locator('[data-source-progress]').innerText()==='1 / 1');
    check('Completed material is read-only',await page.locator('[data-source-save]').isDisabled());
    await page.locator('[data-source-complete]').click();
    await page.getByRole('button',{name:'本份材料编码完成',exact:true}).waitFor();
    check('Material can be reopened before the round ends',await page.locator('[data-source-save]').isEnabled());
    const exported=await context.request.get(`${base}/source-rounds/${round}/export/?format=json`);
    check('Saved excerpts export before completion',exported.status()===200&&(await exported.text()).includes('第二个独立片段'));
    await page.reload();
    check('Saved highlights survive reload',await page.locator('mark[data-source-annotations]').count()>=2);
    for(const width of [1366,1024,768,390,320]) {
      await page.setViewportSize({width,height:900});
      check(`Fits ${width}px without page overflow`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    }
    await page.screenshot({path:output+'/workbench-mobile.png',fullPage:true});
    await page.setViewportSize({width:1440,height:900});
    await page.goto(`${base}/p/${project}/history/`);
    check('My history includes source excerpts',(await page.locator('main').innerText()).includes('原文选段记录'));
    await page.getByRole('link',{name:'修改历史',exact:true}).first().click();
    await page.locator('.source-history-event').waitFor();
    check('History links open readable revision details',await page.locator('[data-source-history]').isVisible());
    await page.locator('[data-source-history-close]').click();
    await page.goto(`${base}/p/${project}/exports/`);
    check('Export center links the original-text results',(await page.locator('main').innerText()).includes('我的原文选段编码'));
    await page.goto(base+'/projects/');
    check('Project list resumes original-text work',(await page.locator('main').innerText()).includes('继续原文编码'));
    await page.goto(base+'/projects/new/');
    await page.locator('[name=name]').fill('逐条开放编码 · 虚构资料 '+Date.now());
    await page.getByRole('button',{name:'创建项目',exact:true}).click();
    await page.waitForURL(/\/p\/\d+\/$/);
    const unitProject=Number(page.url().match(/\/p\/(\d+)\//)[1]);
    const bookUrl=await page.locator(`a[href^="/p/${unitProject}/books/"]`).first().getAttribute('href');
    await page.goto(base+bookUrl);
    await page.getByText('标签方式设置',{exact:true}).click();
    await page.locator('form[action$="/policy/"] [name=policy]').selectOption('parallel');
    await page.getByRole('button',{name:'保存标签方式',exact:true}).click();
    await page.waitForLoadState('load');
    await page.goto(`${base}/p/${unitProject}/materials/`);
    await page.locator('input[type=file]').setInputFiles({name:'fiction-dialogue.csv',mimeType:'text/csv',buffer:Buffer.from('text,speaker\n先核对证据,甲\n再讨论结论,乙\n')});
    await page.getByRole('button',{name:'上传并预览 →',exact:true}).click();
    await page.getByRole('button',{name:'确认导入',exact:true}).click();
    await page.waitForLoadState('load');
    await page.goto(`${base}/p/${unitProject}/quick-start/`);
    await page.getByRole('button',{name:'开始个人编码 →',exact:true}).click();
    await page.waitForURL(/\/r\/\d+\//);
    await page.locator('.workspace-code-add summary').click();
    await page.locator('.workspace-code-create [name=name]').fill('核对依据');
    await Promise.all([page.waitForURL(/new_code=/),page.getByRole('button',{name:'添加并使用',exact:true}).click()]);
    await page.waitForFunction(()=>document.querySelector('.annotation-form [name=labels]:checked'));
    check('Existing unit workflow adds and selects a new parallel code',await page.locator('.annotation-form [name=labels]:checked').count()===1);
    await page.locator('.workspace-code-add summary').click();
    await page.locator('.workspace-code-create [name=name]').fill('提出行动');
    const priorCode=new URL(page.url()).searchParams.get('new_code');
    await Promise.all([page.waitForURL(url=>new URL(url).searchParams.get('new_code')!==priorCode),page.getByRole('button',{name:'添加并使用',exact:true}).click()]);
    await page.waitForFunction(()=>document.querySelectorAll('.annotation-form [name=labels]:checked').length===2);
    check('Multiple parallel codes retain the first choice after adding another',await page.locator('.annotation-form [name=labels]:checked').count()===2);
    await page.locator('[data-action=submit_next]').click();
    await page.waitForFunction(()=>document.querySelector('.annotation-form [name=labels]:checked')===null);
    check('Original confirm-and-next still advances without new mandatory steps');
    check('No uncaught browser errors',errors.length===0);
    fs.writeFileSync(output+'/browser-result.json',JSON.stringify({passed:checks.length,checks,errors,project,round},null,2));
    console.log(`Passed ${checks.length} source-coding browser checks.`);
  } catch(error) { fs.writeFileSync(output+'/failure.json',JSON.stringify({errors,url:page.url(),checks},null,2));await page.screenshot({path:output+'/failure.png',fullPage:true});throw error; }
  finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
