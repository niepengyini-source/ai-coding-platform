// Only the isolated synthetic UI server and fictional-policy.docx fixture are used.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {spawnSync} = require('node:child_process');
const {chromium} = require('playwright');
(async () => {
  const base='http://127.0.0.1:8001', c=JSON.parse(fs.readFileSync('runtime/workbench-ui.json','utf8'));
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  const context=await browser.newContext({viewport:{width:1440,height:900}}), page=await context.newPage();
  const checks=[], errors=[];
  page.on('pageerror', error=>errors.push(error.message));
  const check=(label,value=true)=>{assert.ok(value,label);checks.push(label);};
  fs.mkdirSync('runtime/document-review',{recursive:true});
  try {
    await page.goto(base+'/login/');
    check('isolated QA cookie', (await context.cookies()).some(x=>x.name==='ui_csrftoken'));
    await page.locator('[name=username]').fill(c.username);
    await page.locator('[name=password]').fill(c.password);
    await Promise.all([page.waitForURL(base+'/'),page.getByRole('button',{name:'登录',exact:true}).click()]);
    await page.goto(base+'/projects/new/');
    await page.locator('[name=name]').fill('虚构政策编码 '+Date.now());
    await page.getByRole('button',{name:'创建项目',exact:true}).click();
    await page.waitForURL(/\/p\/\d+\/$/);
    const project=Number(page.url().match(/\/p\/(\d+)\//)[1]);
    await page.goto(`${base}/p/${project}/materials/`);
    await page.locator('input[type=file]').setInputFiles('runtime/fictional-policy.docx');
    await page.getByRole('button',{name:'上传并预览 →',exact:true}).click();
    await page.getByText('推荐使用全文阅读工作台',{exact:true}).waitFor();
    check('document import explains review before creating coding units');
    await page.getByRole('button',{name:'确认导入',exact:true}).click();
    await page.waitForURL(/\/source-coding\//);
    const doc=Number(new URL(page.url()).searchParams.get('document'));
    check('import allows coding before manual preparation',await page.getByRole('heading',{name:'阅读原文，随时划选编码'}).isVisible());
    const prepareUrl=`${base}/p/${project}/materials/${doc}/prepare/`;
    await page.goto(prepareUrl);
    check('unified preparation remains an optional tool',await page.locator('[data-document-reading]').isVisible());
    async function select(first,last){
      await page.locator('[data-document-text]').nth(first).scrollIntoViewIfNeeded();
      await page.evaluate(({first,last})=>{
        const nodes=document.querySelectorAll('[data-document-text]');
        const start=document.createTreeWalker(nodes[first],NodeFilter.SHOW_TEXT).nextNode();
        const end=document.createTreeWalker(nodes[last],NodeFilter.SHOW_TEXT).nextNode();
        const range=document.createRange();range.setStart(start,0);range.setEnd(end,end.textContent.length);
        const s=getSelection();s.removeAllRanges();s.addRange(range);
        document.querySelector('[data-document-reading]').dispatchEvent(new MouseEvent('mouseup',{bubbles:true}));
      },{first,last});
      check('selection can be added',await page.locator('[data-add-selection]').isEnabled());
      return page.locator('[data-selection-preview]').innerText();
    }
    const selected=await select(1,2);
    check('cross-paragraph Unicode selection retains emoji and both clauses',selected.includes('😀')&&selected.includes('第1条')&&selected.includes('第2条'));
    await page.locator('[data-add-selection]').click();
    await page.waitForLoadState('load');
    check('candidate is present before confirmation',await page.locator('.document-fragment-list li').count()===1 && await page.locator('.document-fragment-empty').count()===0);
    await page.getByRole('button',{name:'撤回上次修改',exact:true}).click();
    await page.waitForLoadState('load');
    check('candidate edit can be undone',await page.locator('.document-fragment-empty').count()===1);
    await select(1,2);await page.locator('[data-add-selection]').click();await page.waitForLoadState('load');
    await select(3,3);await page.locator('[data-add-selection]').click();await page.waitForLoadState('load');
    await page.screenshot({path:'runtime/document-review/prepare-desktop.png'});
    await page.getByRole('button',{name:'确认统一片段',exact:true}).click();await page.waitForLoadState('load');
    check('confirmed fragments expose existing task entry',await page.getByRole('link',{name:'安排成员任务',exact:true}).isVisible());
    const result=spawnSync('.venv/Scripts/python.exe',['-X','utf8','-B','runtime/document_round_fixture.py',String(doc)],{encoding:'utf8'});
    assert.equal(result.status,0,result.stderr); const r=JSON.parse(result.stdout.trim());
    await page.goto(`${base}/r/${r.round}/?a=${r.assignment}`);
    await page.locator('[data-task-queue-app] .task-queue').waitFor();
    check('document workbench opens full text by default',await page.locator('#reading-document').isVisible());
    check('current shared fragment is highlighted',await page.locator('#reading-document mark').count()>=2);
    check('toolbar leaves the workspace near the top',(await page.locator('.workbench-grid').boundingBox()).y<=110);
    await page.getByRole('tab',{name:'当前单元',exact:true}).click();
    check('unit view remains available',await page.locator('#current-unit-text').isVisible());
    await page.getByRole('tab',{name:'阅读全文',exact:true}).click();
    await page.keyboard.press('Alt+q');
    check('quick coding works in document mode',await page.locator('.annotation-form').getAttribute('data-quick-mode')==='true');
    await page.getByRole('button',{name:'收起代码选择',exact:true}).click();
    check('mouse coding keeps quick mode',await page.locator('.annotation-form').getAttribute('data-quick-mode')==='true');
    await page.locator('.code-choice').first().click();
    await page.locator('[name=note]').fill('虚构长文编码验证');
    await page.waitForFunction(()=>document.querySelector('.save-status').classList.contains('success'));
    await page.screenshot({path:'runtime/document-review/workbench-desktop.png'});
    const before=page.url();
    await page.locator('[data-action=submit_next]').click();
    await page.waitForURL(url=>url.toString()!==before);
    check('same confirmation flow submits and locates the next task',page.url().includes(`/r/${r.round}/`));
    check('full text stays the default on next unit',await page.locator('#reading-document').isVisible());
    const download=await context.request.get(`${base}/r/${r.round}/export/mine/`);
    check('existing own export still works',download.status()===200&&(await download.body()).includes(Buffer.from('虚构长文编码验证')));
    await page.setViewportSize({width:390,height:844});
    check('document workbench fits a narrow screen',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:'runtime/document-review/workbench-mobile.png'});
    await page.goto(prepareUrl);
    check('preparation remains reachable after assigning tasks',await page.locator('[data-document-reading]').isVisible());
    check('preparation fits a narrow screen',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:'runtime/document-review/prepare-mobile.png'});
    await page.setViewportSize({width:1440,height:900});
    await page.goto(`${base}/r/${r.round}/?a=${r.assignment}`);
    await page.locator('.document-coding-entry').waitFor({state:'visible'});
    check('Full-text view exposes selection coding without opening a menu');
    await page.locator('.material-scroll').evaluate(element=>{element.scrollTop=element.scrollHeight;});
    check('Selection entry stays visible while reading long text',await page.locator('.document-coding-entry').isVisible());
    await page.screenshot({path:'runtime/document-review/selection-entry.png'});
    await page.locator('.document-coding-entry').click();
    await page.waitForURL(/\/source-coding\//);
    check('Existing material opens directly without reimport',Number(new URL(page.url()).searchParams.get('document'))===doc);
    await page.getByRole('button',{name:'使用当前编码本开始编码',exact:true}).click();
    await page.waitForURL(/\/r\/\d+\//);
    await page.locator('[data-source-text]').nth(1).scrollIntoViewIfNeeded();
    await page.evaluate(()=>{
      const paragraph=document.querySelectorAll('[data-source-text]')[1], range=document.createRange();
      range.selectNodeContents(paragraph);getSelection().removeAllRanges();getSelection().addRange(range);
      document.querySelector('[data-source-reading]').dispatchEvent(new MouseEvent('mouseup',{bubbles:true}));
    });
    await page.locator('[data-source-selection-text]').waitFor({state:'visible'});
    await page.locator('[data-source-code-list] [name=primary]').first().check();
    await page.locator('#source-note').fill('虚构既有任务材料：验证划选入口与保存。');
    const saved=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().includes('/annotations/'));
    await page.locator('[data-source-save]').click();
    check('Existing-project material supports real excerpt saving',(await saved).status()===200);
    await page.waitForFunction(()=>document.querySelector('[data-source-status]').dataset.kind==='success');
    check('Saved fragment appears in the right coding pane',await page.locator('[data-source-selection-text]').isVisible()&&await page.locator('mark[data-source-annotations]').count()>0);
    await page.screenshot({path:'runtime/document-review/selection-saved.png'});
    const sourceWorkbench=page.url();
    await page.getByRole('link',{name:'全部编码任务',exact:true}).click();
    await page.waitForURL(/#project-rounds$/);
    check('All-task entry exposes the old and new work together',await page.locator(`#project-rounds a[href="/r/${r.round}/"]`).count()===1&&(await page.locator('#project-rounds').innerText()).includes('原文选段'));
    await page.locator(`#project-rounds a[href="/r/${r.round}/"]`).click();
    await page.locator(`[data-task-queue-app] a[href*="a=${r.assignment}"]`).click();
    await page.waitForFunction(()=>document.querySelector('.annotation-form [name=note]').value==='虚构长文编码验证');
    check('Returning to the old task keeps its original answer',await page.locator('.annotation-form [name=note]').inputValue()==='虚构长文编码验证');
    await page.goto(sourceWorkbench);
    await page.getByLabel('工作台工具',{exact:true}).click();
    await page.getByRole('link',{name:'我的编码历史',exact:true}).click();
    await page.waitForURL(/\/history\/$/);
    check('History keeps both old unit judgments and new excerpts',(await page.locator('main').innerText()).includes('虚构长文编码验证')&&(await page.locator('main').innerText()).includes('原文选段记录'));
    check('no browser script errors',errors.length===0);
    fs.writeFileSync('runtime/document-review/browser-result.json',JSON.stringify({passed:checks.length,checks},null,2));
    console.log(`Passed ${checks.length} document browser checks.`);
  } catch(error) {await page.screenshot({path:'runtime/document-review/failure.png',fullPage:true});throw error;}
  finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
